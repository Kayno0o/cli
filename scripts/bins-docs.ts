import type { Description } from '../packages/kit/src/args'
import { basename, dirname } from 'node:path'
import { bins, run } from '../tests/bins'

// The cheat sheet of every bin, read off the `describe` JSON each prints under KIT_HELP=json: what it is for, what it replaces and its examples.
export function binsMarkdown(): string {
  const sections = bins.toSorted((a, b) => a.bin.localeCompare(b.bin)).map(({ bin, source }) => {
    const described = JSON.parse(run(source, ['--help'], { KIT_HELP: 'json' })) as Description
    const examples = described.examples.map(({ line, note }) => note === undefined ? line : `${line}  # ${note}`)

    return [
      `## ${bin}`,
      '',
      `${described.summary}. Package \`${basename(dirname(dirname(source)))}\`.`,
      ...described.replaces === undefined ? [] : ['', `Instead of: ${described.replaces}`],
      '',
      '```sh',
      described.synopsis,
      ...examples,
      '```',
    ].join('\n')
  })

  return `# Bins\n\nGenerated by \`bun run docs\` from each bin's \`--help\` description, do not edit.\n\n${sections.join('\n\n')}\n`
}

if (import.meta.main)
  await Bun.write(new URL('../docs/bins.md', import.meta.url), binsMarkdown())
