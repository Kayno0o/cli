import type { Description } from '../packages/kit/src/args'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { bins as allBins, run } from '../tests/bins'

interface PackageManifest {
  name?: string
  description?: string
  bin?: Record<string, string> | string
}

const ROOT = new URL('..', import.meta.url).pathname
const PACKAGES = join(ROOT, 'packages')
const DOCTOR_OUT = join(PACKAGES, 'doctor', 'src', 'generated-catalog.ts')
const GUARD_OUT = join(PACKAGES, 'guard', 'src', 'generated-bins.ts')

const dirs = readdirSync(PACKAGES, { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => entry.name).toSorted()
const tools: [string, string[]][] = []
const about: [string, string][] = []

for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(join(PACKAGES, dir, 'package.json'), 'utf8')) as PackageManifest

  if (pkg.name === undefined || pkg.bin === undefined)
    continue

  const bins = typeof pkg.bin === 'string' ? [pkg.name.slice(pkg.name.indexOf('/') + 1)] : Object.keys(pkg.bin)

  tools.push([pkg.name, bins])
  about.push([pkg.name, pkg.description ?? ''])
}

tools.sort(([a], [b]) => a.localeCompare(b))
about.sort(([a], [b]) => a.localeCompare(b))

const quote = (value: string) => `'${value.replaceAll('\\', '\\\\').replaceAll('\'', '\\\'')}'`

const IDENT = /^[a-z_$][\w$]*$/i
const propKey = (value: string) => IDENT.test(value) ? value : quote(value)
const WHITESPACE = /\s+/g

function shorten(text: string, max: number): string {
  const clean = text.replace(WHITESPACE, ' ').trim()

  if (clean.length <= max)
    return clean

  const cut = clean.slice(0, max)
  const sep = Math.max(cut.lastIndexOf('; '), cut.lastIndexOf(', '), cut.lastIndexOf(' '))

  return `${(sep > max * 0.5 ? cut.slice(0, sep) : cut).trimEnd()}…`
}

const doctorLines = [
  '// Generated by `bun scripts/catalog.ts` from packages/*/package.json — do not edit by hand.',
  'export const TOOLS: Record<string, string[]> = {',
  ...tools.map(([name, bins]) => `  ${quote(name)}: [${bins.map(quote).join(', ')}],`),
  '}',
  '',
  'export const ABOUT: Record<string, string> = {',
  ...about.map(([name, desc]) => `  ${quote(name)}: ${quote(desc)},`),
  '}',
  '',
]

writeFileSync(DOCTOR_OUT, doctorLines.join('\n'))

const binEntries = allBins
  .toSorted((a, b) => a.bin.localeCompare(b.bin))
  .map(({ bin, source }) => {
    const described = JSON.parse(run(source, ['--help'], { KIT_HELP: 'json' })) as Description
    const summary = shorten(described.summary, 64)
    const replaces = described.replaces === undefined ? undefined : shorten(described.replaces, 36)

    return { bin, summary, replaces }
  })

const guardLines = [
  '// Generated by `bun scripts/catalog.ts` from each bin\'s KIT_HELP=json — do not edit by hand.',
  'export interface BinBrief { summary: string, replaces?: string }',
  '',
  'export const GENERATED_BINS: Record<string, BinBrief> = {',
  ...binEntries.map(({ bin, summary, replaces }) => `  ${propKey(bin)}: { summary: ${quote(summary)}${replaces === undefined ? '' : `, replaces: ${quote(replaces)}`} },`),
  '}',
  '',
]

writeFileSync(GUARD_OUT, guardLines.join('\n'))
