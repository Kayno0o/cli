import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

interface PackageManifest {
  name?: string
  description?: string
  bin?: Record<string, string> | string
}

const ROOT = new URL('..', import.meta.url).pathname
const PACKAGES = join(ROOT, 'packages')
const OUT = join(PACKAGES, 'doctor', 'src', 'generated-catalog.ts')

const dirs = readdirSync(PACKAGES, { withFileTypes: true }).filter(entry => entry.isDirectory()).map(entry => entry.name).toSorted()
const tools: [string, string[]][] = []
const about: [string, string][] = []

for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(join(PACKAGES, dir, 'package.json'), 'utf8')) as PackageManifest

  if (pkg.name === undefined || pkg.bin === undefined)
    continue

  const bins = typeof pkg.bin === 'string' ? [pkg.name.slice(pkg.name.indexOf('/') + 1)] : Object.keys(pkg.bin)

  tools.push([pkg.name, bins])
  about.push([pkg.name, pkg.description ?? ''])
}

tools.sort(([a], [b]) => a.localeCompare(b))
about.sort(([a], [b]) => a.localeCompare(b))

const quote = (value: string) => `'${value.replaceAll('\\', '\\\\').replaceAll('\'', '\\\'')}'`

const lines = [
  '// Generated by `bun scripts/catalog.ts` from packages/*/package.json — do not edit by hand.',
  'export const TOOLS: Record<string, string[]> = {',
  ...tools.map(([name, bins]) => `  ${quote(name)}: [${bins.map(quote).join(', ')}],`),
  '}',
  '',
  'export const ABOUT: Record<string, string> = {',
  ...about.map(([name, desc]) => `  ${quote(name)}: ${quote(desc)},`),
  '}',
  '',
]

writeFileSync(OUT, lines.join('\n'))
