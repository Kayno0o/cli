import type { Host } from './checks'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { TOOLS } from './checks'

const MARKER = '# Generated by `cli completions fish`'
const FISH_FILE = /\.fish$/

// What a bin offers for the word being typed is asked of the bin itself, `<bin> __complete`, see @kaynooo/cli-kit.
const FUNCTION = `functions -q __kaynooo_cli_complete; or function __kaynooo_cli_complete --argument-names bin --description 'what a @kaynooo/cli-* bin offers for the word being typed'
    set -l tokens (commandline -xpc 2>/dev/null; or commandline -opc)
    set -l current (commandline -ct)
    for line in ($bin __complete $tokens[2..-1] $current 2>/dev/null)
        if test "$line" = __files__
            __fish_complete_path $current
        else
            echo $line
        end
    end
end`

const BASH_FUNCTION = `__kaynooo_cli_complete() {
    local IFS=$'\\n' cur=\${COMP_WORDS[COMP_CWORD]} line words=
    local -a lines
    COMPREPLY=()
    lines=($("\${COMP_WORDS[0]}" __complete "\${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null))
    for line in "\${lines[@]}"; do
        if [[ $line == __files__ ]]; then
            COMPREPLY+=($(compgen -f -- "$cur"))
        else
            words+="\${line%%$'\\t'*}"$'\\n'
        fi
    done
    COMPREPLY+=($(compgen -W "$words" -- "$cur"))
}`

// The script `source <(cli completions bash)` runs: one function asking the bin itself, registered for each bin.
export function bashScript(bins: string[]): string {
  return `# Generated by \`cli completions bash\`\n${BASH_FUNCTION}\ncomplete -F __kaynooo_cli_complete ${bins.join(' ')}\n`
}

// The folder fish is told to read completions from first, so a file there shadows one fish ships for the same name (its stack.fish is Haskell Stack's).
export function completionDir(home: string, env: Record<string, string | undefined> = process.env): string {
  return join(env.XDG_CACHE_HOME ?? join(home, '.cache'), 'fish', 'kaynooo-cli')
}

// Every bin of the packages installed here, in the order of TOOLS.
export function installedBins(host: Host): string[] {
  return Object.values(TOOLS).flat().filter(bin => host.which(bin) !== null)
}

// One bin's file, complete on its own: the function is defined unless an earlier file did.
export function completionFile(bin: string): string {
  return `${MARKER}\n${FUNCTION}\ncomplete -c ${bin} -f -a '(__kaynooo_cli_complete ${bin})'\n`
}

// The files `cli completions fish --install` leaves in the folder, and the stale ones of ours it takes out; a file it did not write stays.
export async function installCompletions(host: Host, dir: string): Promise<{ written: string[], removed: string[] }> {
  const bins = installedBins(host)

  mkdirSync(dir, { recursive: true })

  const removed = readdirSync(dir).filter(name => FISH_FILE.test(name) && !bins.includes(name.replace(FISH_FILE, '')) && readFileSync(join(dir, name), 'utf8').startsWith(MARKER))

  for (const name of removed)
    rmSync(join(dir, name))

  await Promise.all(bins.map(async bin => Bun.write(join(dir, `${bin}.fish`), completionFile(bin))))

  return { written: bins, removed: removed.map(name => name.replace(FISH_FILE, '')) }
}

// The installed bins with no completion file in the folder.
export function missingCompletions(host: Host, dir: string): string[] {
  return installedBins(host).filter(bin => !existsSync(join(dir, `${bin}.fish`)))
}
