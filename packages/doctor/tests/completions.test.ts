import type { Host } from '../src/checks'
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { capture, tempDirs } from '@kaynooo/cli-kit/test'
import { describe, expect, test } from 'bun:test'
import { checkCompletions } from '../src/checks'
import { completions } from '../src/cli-bin'
import { bashScript, completionDir, completionFile, installCompletions, installedBins, missingCompletions } from '../src/completions'

const temp = tempDirs()

function hostWith(onPath: string[], home = '/home/x'): Host {
  return { home, globalModules: '/none', bunVersion: '1.4.4', which: bin => onPath.includes(bin) ? `/bin/${bin}` : null, run: async () => ({ code: 0, stdout: '', stderr: '' }) }
}

describe('completionFile', () => {
  test('defines the function once and completes the bin through it', () => {
    const file = completionFile('peek')

    expect(file).toStartWith('# Generated by `cli completions fish`\nfunctions -q __kaynooo_cli_complete; or function __kaynooo_cli_complete')
    expect(file).toContain('$bin __complete $tokens[2..-1] $current')
    expect(file).toEndWith('complete -c peek -f -a \'(__kaynooo_cli_complete peek)\'\n')
  })
})

describe('completionDir', () => {
  test('is the fish folder of the cache, XDG_CACHE_HOME first', () => {
    expect(completionDir('/home/x', {})).toBe('/home/x/.cache/fish/kaynooo-cli')
    expect(completionDir('/home/x', { XDG_CACHE_HOME: '/c' })).toBe('/c/fish/kaynooo-cli')
  })
})

describe('installCompletions', () => {
  test('writes a file per installed bin and takes out the stale ones it wrote, not a file it did not', async () => {
    const dir = temp('completions-')
    const host = hostWith(['peek', 'gst', 'view'])

    expect(installedBins(host)).toEqual(['peek', 'gst', 'view'])
    writeFileSync(join(dir, 'old.fish'), completionFile('old'))
    writeFileSync(join(dir, 'mine.fish'), 'complete -c mine -f\n')
    writeFileSync(join(dir, 'peek.fish'), 'complete -c peek -f -a x\n')

    const { written, removed } = await installCompletions(host, dir)

    expect(written).toEqual(['peek', 'gst', 'view'])
    expect(removed).toEqual(['old'])
    expect(readFileSync(join(dir, 'peek.fish'), 'utf8')).toBe(completionFile('peek'))
    expect(existsSync(join(dir, 'mine.fish'))).toBe(true)

    expect((await installCompletions(hostWith(['gst']), dir)).removed.sort()).toEqual(['peek', 'view'])
    expect(existsSync(join(dir, 'peek.fish'))).toBe(false)
  })
})

describe('checkCompletions', () => {
  test('passes without fish, fails for a bin with no file and passes once installed', async () => {
    const home = temp('completions-home-')

    expect(checkCompletions(hostWith(['peek'], home)).ok).toBe(true)

    const host = hostWith(['fish', 'peek', 'gst'], home)
    const failed = checkCompletions(host)

    expect(failed).toMatchObject({ ok: false, fix: 'cli completions fish --install' })
    expect(failed.detail).toContain('peek, gst')
    expect(missingCompletions(host, completionDir(home))).toEqual(['peek', 'gst'])

    mkdirSync(completionDir(home), { recursive: true })
    await installCompletions(host, completionDir(home))
    expect(checkCompletions(host).ok).toBe(true)
  })
})

describe('cli completions', () => {
  test('prints the files, or writes them with --install and --dir', async () => {
    const host = hostWith(['peek', 'gst'])
    const printed = await capture(async () => completions(['fish'], host))

    expect(printed.result).toBe(0)
    expect(printed.out).toContain('complete -c peek')
    expect(printed.out).toContain('complete -c gst')

    const dir = temp('completions-out-')
    const written = await capture(async () => completions(['fish', '--install', '--dir', dir], host))

    expect(written.out).toContain('wrote 2 completions')
    expect(existsSync(join(dir, 'gst.fish'))).toBe(true)
  })
})

async function refusal(run: () => Promise<unknown>): Promise<Error | undefined> {
  try {
    await run()
  }
  catch (error) {
    return error as Error
  }

  return undefined
}

describe('bashScript', () => {
  // A bin standing in for a @kaynooo one: it answers `__complete` with a command, a description and a path marker.
  function fakeBin(): string {
    const dir = temp('completions-bin-')
    const script = join(dir, 'demo')

    writeFileSync(script, '#!/bin/sh\ncase "$*" in\n  "__complete "|"__complete be") printf "build\\tbuild it\\nbench\\tbench it\\nrun\\n" ;;\n  "__complete build --") printf -- "--fast\\tquick\\n--full\\n" ;;\n  "__complete run "*) printf "__files__\\n" ;;\nesac\n')
    chmodSync(script, 0o755)

    return dir
  }

  function reply(dir: string, words: string[], cur: number): string[] {
    const script = bashScript(['demo'])
    const quoted = words.map(word => `'${word}'`).join(' ')
    const ran = Bun.spawnSync(['bash', '-c', `${script}\nCOMP_WORDS=(${quoted}); COMP_CWORD=${cur}; __kaynooo_cli_complete; printf '%s\\n' "\${COMPREPLY[@]}"`], { cwd: dir, env: { ...process.env, PATH: `${dir}:${process.env.PATH}` } })

    return ran.stdout.toString().split('\n').filter(line => line !== '')
  }

  test('registers every bin on one function', () => {
    expect(bashScript(['peek', 'gst'])).toStartWith('# Generated by `cli completions bash`\n')
    expect(bashScript(['peek', 'gst'])).toEndWith('complete -F __kaynooo_cli_complete peek gst\n')
  })

  test('offers the commands the bin names, filtered by the word typed and without their descriptions', () => {
    const dir = fakeBin()

    expect(reply(dir, ['demo', ''], 1)).toEqual(['build', 'bench', 'run'])
    expect(reply(dir, ['demo', 'be'], 1)).toEqual(['bench'])
  })

  test('offers the options of a command, and the files where the bin asks for a path', () => {
    const dir = fakeBin()

    writeFileSync(join(dir, 'notes.txt'), '')

    expect(reply(dir, ['demo', 'build', '--'], 2)).toEqual(['--fast', '--full'])
    expect(reply(dir, ['demo', 'run', 'no'], 2)).toEqual(['notes.txt'])
  })
})

describe('cli completions bash', () => {
  test('prints the script for the installed bins, and refuses --install', async () => {
    const host = hostWith(['peek', 'gst'])
    const printed = await capture(async () => completions(['bash'], host))

    expect(printed.out).toContain('complete -F __kaynooo_cli_complete peek gst')
    expect((await refusal(async () => completions(['bash', '--install'], host)))?.message).toContain('fish')
  })

  test('points zsh at the bash script', async () => {
    expect((await refusal(async () => completions(['zsh'], hostWith([]))))?.message).toContain('bashcompinit')
  })
})
