import { chmodSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import process from 'node:process'
import { describe, expect, test } from 'bun:test'
import { completionScript, runCli, runMain } from '../src'
import { capture, tempDirs } from '../src/test'

const temp = tempDirs()

// A bin standing in for one built on kit: it answers `__complete` with commands, a description and the path marker.
function fakeBin(): string {
  const dir = temp('completions-bin-')
  const script = join(dir, 'demo')

  writeFileSync(script, '#!/bin/sh\ncase "$*" in\n  "__complete "|"__complete be") printf "build\\tbuild it\\nbench\\tbench it\\nrun\\n" ;;\n  "__complete build --") printf -- "--fast\\tquick\\n--full\\n" ;;\n  "__complete run "*) printf "__files__\\n" ;;\nesac\n')
  chmodSync(script, 0o755)
  writeFileSync(join(dir, 'notes.txt'), '')

  return dir
}

function onPath(dir: string): Record<string, string | undefined> {
  return { ...process.env, PATH: `${dir}:${process.env.PATH}` }
}

describe('completionScript', () => {
  test('names the bin\'s own flag in its header unless given one', () => {
    expect(completionScript('fish', ['demo'])).toStartWith('# Generated by `demo --completions fish`\nfunctions -q __kaynooo_cli_complete; or function __kaynooo_cli_complete')
    expect(completionScript('bash', ['demo', 'ft'], '# mine')).toStartWith('# mine\n__kaynooo_cli_complete() {')
  })

  test('registers every bin on the one function', () => {
    expect(completionScript('fish', ['src', 'gst'])).toEndWith('end\ncomplete -c src -f -a \'(__kaynooo_cli_complete src)\'\ncomplete -c gst -f -a \'(__kaynooo_cli_complete gst)\'\n')
    expect(completionScript('bash', ['src', 'gst'])).toEndWith('complete -F __kaynooo_cli_complete src gst\n')
    expect(completionScript('zsh', ['src', 'gst'])).toEndWith('compdef __kaynooo_cli_complete src gst\n')
  })

  test('zsh describes the values with one, escaping their colons, and completes files on the marker', () => {
    const script = completionScript('zsh', ['demo'])

    expect(script).toContain('_describe -V value described')
    expect(script).toContain('//:/\\\\:')
    expect(script).toContain('__files__')
  })
})

describe.if(Bun.which('bash') !== null)('the bash script', () => {
  function reply(dir: string, words: string[], cur: number): string[] {
    const quoted = words.map(word => `'${word}'`).join(' ')
    const ran = Bun.spawnSync(['bash', '-c', `${completionScript('bash', ['demo'])}\nCOMP_WORDS=(${quoted}); COMP_CWORD=${cur}; __kaynooo_cli_complete; printf '%s\\n' "\${COMPREPLY[@]}"`], { cwd: dir, env: onPath(dir) })

    return ran.stdout.toString().split('\n').filter(line => line !== '')
  }

  test('offers the commands the bin names, filtered by the word typed and without their descriptions', () => {
    const dir = fakeBin()

    expect(reply(dir, ['demo', ''], 1)).toEqual(['build', 'bench', 'run'])
    expect(reply(dir, ['demo', 'be'], 1)).toEqual(['bench'])
  })

  test('offers the options of a command, and the files where the bin asks for a path', () => {
    const dir = fakeBin()

    expect(reply(dir, ['demo', 'build', '--'], 2)).toEqual(['--fast', '--full'])
    expect(reply(dir, ['demo', 'run', 'no'], 2)).toEqual(['notes.txt'])
  })
})

describe.if(Bun.which('fish') !== null)('the fish script', () => {
  function reply(dir: string, line: string): string[] {
    const script = join(dir, 'demo.fish')

    writeFileSync(script, completionScript('fish', ['demo']))

    const ran = Bun.spawnSync(['fish', '--no-config', '-c', `source ${script}; complete -C '${line}'`], { cwd: dir, env: onPath(dir) })

    return ran.stdout.toString().split('\n').filter(each => each !== '')
  }

  test('offers the commands with their descriptions, the options of a command and the files', () => {
    const dir = fakeBin()

    expect(reply(dir, 'demo be')).toEqual(['bench\tbench it'])
    expect(reply(dir, 'demo build --')).toEqual(['--fast\tquick', '--full'])
    expect(reply(dir, 'demo run no')).toEqual(['notes.txt'])
  })
})

describe('--completions', () => {
  const cli = { name: 'demo', version: '1.0.0', about: 'a demo', commands: { echo: { summary: 'echoes', run: async () => 0 } } }

  test('runCli prints the bin\'s own script for the shell named, = or not', async () => {
    const printed = await capture(async () => runCli(cli, ['--completions', 'bash']))

    expect(printed).toMatchObject({ result: 0, out: completionScript('bash', ['demo']) })
    expect((await capture(async () => runCli(cli, ['--completions=fish']))).out).toBe(completionScript('fish', ['demo']))
  })

  test('runMain prints it too', async () => {
    expect((await capture(async () => runMain({ name: 'solo', run: async () => 0 }, ['--completions', 'zsh']))).out).toBe(completionScript('zsh', ['solo']))
  })

  test('refuses a shell it has no script for, or none', async () => {
    expect(await capture(async () => runCli(cli, ['--completions', 'nu']))).toMatchObject({ result: 2, err: expect.stringContaining('--completions takes one of fish, bash, zsh') })
    expect((await capture(async () => runMain({ name: 'solo', run: async () => 0 }, ['--completions']))).result).toBe(2)
  })

  test('is listed in the top help with its shells', async () => {
    expect((await capture(async () => runCli(cli, ['--help']))).out).toContain('--completions <fish|bash|zsh>')
  })
})
