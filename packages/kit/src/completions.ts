// The shells `<bin> --completions <shell>` writes a script for.
export const COMPLETION_SHELLS = ['fish', 'bash', 'zsh'] as const
export type CompletionShell = typeof COMPLETION_SHELLS[number]

// What a bin offers for the word being typed is asked of the bin itself, `<bin> __complete`; the function is shared by every bin built on @kaynooo/cli-kit, so it is defined once.
const FISH_FUNCTION = `functions -q __kaynooo_cli_complete; or function __kaynooo_cli_complete --argument-names bin --description 'what a @kaynooo/cli-kit bin offers for the word being typed'
    set -l tokens (commandline -xpc 2>/dev/null; or commandline -opc)
    set -l current (commandline -ct)
    for line in ($bin __complete $tokens[2..-1] $current 2>/dev/null)
        if test "$line" = __files__
            __fish_complete_path $current
        else
            echo $line
        end
    end
end`

const BASH_FUNCTION = `__kaynooo_cli_complete() {
    local IFS=$'\\n' cur=\${COMP_WORDS[COMP_CWORD]} line words=
    local -a lines
    COMPREPLY=()
    lines=($("\${COMP_WORDS[0]}" __complete "\${COMP_WORDS[@]:1:COMP_CWORD}" 2>/dev/null))
    for line in "\${lines[@]}"; do
        if [[ $line == __files__ ]]; then
            COMPREPLY+=($(compgen -f -- "$cur"))
        else
            words+="\${line%%$'\\t'*}"$'\\n'
        fi
    done
    COMPREPLY+=($(compgen -W "$words" -- "$cur"))
}`

const ZSH_FUNCTION = `__kaynooo_cli_complete() {
    local line
    local -a described plain
    for line in \${(f)"$("\${words[1]}" __complete "\${(@)words[2,CURRENT]}" 2>/dev/null)"}; do
        if [[ $line == __files__ ]]; then
            _files
        elif [[ $line == *$'\\t'* ]]; then
            described+=("\${\${line%%$'\\t'*}//:/\\\\:}:\${line#*$'\\t'}")
        else
            plain+=("$line")
        fi
    done
    (( \${#described} )) && _describe -V value described
    (( \${#plain} )) && compadd -- "\${plain[@]}"
    return 0
}`

// The script completing the bins in a shell: fish's saved as `<bin>.fish` in a folder of fish_complete_path, bash's sourced from ~/.bashrc, zsh's sourced after compinit. The header is its first line, naming the command that wrote it.
export function completionScript(shell: CompletionShell, bins: string[], header = `# Generated by \`${bins[0]} --completions ${shell}\``): string {
  if (shell === 'fish')
    return `${header}\n${FISH_FUNCTION}\n${bins.map(bin => `complete -c ${bin} -f -a '(__kaynooo_cli_complete ${bin})'\n`).join('')}`

  if (shell === 'bash')
    return `${header}\n${BASH_FUNCTION}\ncomplete -F __kaynooo_cli_complete ${bins.join(' ')}\n`

  return `${header}\n${ZSH_FUNCTION}\ncompdef __kaynooo_cli_complete ${bins.join(' ')}\n`
}
