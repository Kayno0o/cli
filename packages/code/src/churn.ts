import { runCommand } from '@kaynooo/cli-kit'

export interface Hotspot {
  path: string
  score: number
  churn: number
  complexity: number
  lines: number
}

// Source files only: anything else (docs, data, images, lockfiles) has no branches to count.
const SOURCE = /\.(?:[cm]?[jt]sx?|vue|svelte|astro|py|go|rs|rb|php|java|kt|swift|cs|c|cc|cpp|h|hpp|scala|dart|lua|sh|zsh|fish)$/
const TESTS = /(?:^|\/)(?:tests?|__tests__|spec|e2e|__mocks__|fixtures)\/|\.(?:test|spec|bench)\.[^/]+$|(?:^|\/)test_[^/]+$|_test\.(?:go|py)$/
const GENERATED = /(?:^|\/)(?:dist|build|out|generated|\.nuxt|\.output|\.next)\/|\.min\.[cm]?js$|\.d\.ts$|\.(?:generated|gen)\.[^/]+$|\.pb\.go$|\.snap$/
const GENERATED_HEADER = /@generated|generated by|do not edit/i

const DECISION = /\b(?:if|elif|elsif|for|foreach|while|until|case|when|catch|except|rescue|match|guard|and|or)\b|&&|\|\||\?\?|\?(?=[^.?:])/g
const COMMENT = /\/\*[\s\S]*?\*\/|\/\/[^\n]*|^[ \t]*#[^\n]*/gm
const STRING = /'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`(?:\\.|[^`\\])*`/g

export function isCandidate(path: string): boolean {
  return SOURCE.test(path) && !TESTS.test(path) && !GENERATED.test(path)
}

export function isGenerated(text: string): boolean {
  return GENERATED_HEADER.test(text.slice(0, 400))
}

// Decision points (branches, loops, cases, catches, boolean operators, ternaries) plus one, counted over the text with comments and strings blanked: a cheap cyclomatic estimate that reads every language the same way.
export function complexityOf(text: string): number {
  return 1 + (text.replace(COMMENT, '').replace(STRING, '""').match(DECISION)?.length ?? 0)
}

// Commits touching each file (paths relative to cwd) since the date, from one git log; undefined outside a repository.
export async function churnSince(cwd: string, since: string): Promise<Map<string, number> | undefined> {
  const log = await runCommand(['git', 'log', `--since=${since}`, '--no-renames', '--relative', '--name-only', '--format=', '-z'], { cwd })

  if (log.code !== 0)
    return undefined

  const churn = new Map<string, number>()

  for (const path of log.text.split('\0')) {
    if (path !== '')
      churn.set(path, (churn.get(path) ?? 0) + 1)
  }

  return churn
}
