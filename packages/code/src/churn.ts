import { runCommand } from '@kaynooo/cli-kit'

export interface Hotspot {
  path: string
  score: number
  churn: number
  complexity: number
  lines: number
  // Commits counted by how recent they are.
  recent: number
  // The most complex declaration of the file.
  worst: { name: string, line: number, complexity: number } | undefined
}

// Source files only: anything else (docs, data, images, lockfiles) has no branches to count.
const SOURCE = /\.(?:[cm]?[jt]sx?|vue|svelte|astro|py|go|rs|rb|php|java|kt|swift|cs|c|cc|cpp|h|hpp|scala|dart|lua|sh|zsh|fish)$/
const TESTS = /(?:^|\/)(?:tests?|__tests__|spec|e2e|__mocks__|fixtures)\/|\.(?:test|spec|bench)\.[^/]+$|(?:^|\/)test_[^/]+$|_test\.(?:go|py)$/
const GENERATED = /(?:^|\/)(?:dist|build|out|generated|\.nuxt|\.output|\.next)\/|\.min\.[cm]?js$|\.d\.ts$|\.(?:generated|gen)\.[^/]+$|\.pb\.go$|\.snap$/
const LEADING_NEWLINE = /^\n/
const GENERATED_HEADER = /@generated|generated by|do not edit/i

const DECISION = /\b(?:if|elif|elsif|for|foreach|while|until|case|when|catch|except|rescue|match|guard|and|or)\b|&&|\|\||\?\?|\?(?=[^.?:])/g
const COMMENT = /\/\*[\s\S]*?\*\/|\/\/[^\n]*|^[ \t]*#[^\n]*/gm
const STRING = /'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`(?:\\.|[^`\\])*`/g

export function isCandidate(path: string): boolean {
  return SOURCE.test(path) && !TESTS.test(path) && !GENERATED.test(path)
}

export function isGenerated(text: string): boolean {
  return GENERATED_HEADER.test(text.slice(0, 400))
}

// Decision points (branches, loops, cases, catches, boolean operators, ternaries) plus one, counted over the text with comments and strings blanked: a cheap cyclomatic estimate that reads every language the same way.
export function complexityOf(text: string): number {
  return 1 + (text.replace(COMMENT, '').replace(STRING, '""').match(DECISION)?.length ?? 0)
}

export interface Churn {
  commits: number
  // The commits counted by how recent they are, a bulk one left out.
  weight: number
}

export interface ChurnOptions {
  // A commit touching more files than this (a format or rename sweep) says nothing about one of them.
  bulk: number
  // How long until a commit counts half as much; 0 counts them all the same.
  halfLifeMs: number
  now?: number
}

// Commits touching each file (paths relative to cwd) since the date, from one git log; undefined outside a repository.
export async function churnSince(cwd: string, since: string, { bulk, halfLifeMs, now = Date.now() }: ChurnOptions): Promise<Map<string, Churn> | undefined> {
  const log = await runCommand(['git', 'log', `--since=${since}`, '--no-renames', '--relative', '--name-only', '--format=%x01%ct', '-z'], { cwd })

  if (log.code !== 0)
    return undefined

  const churn = new Map<string, Churn>()

  for (const commit of log.text.split('\x01').slice(1)) {
    const [stamp = '', ...names] = commit.split('\0')
    const paths = names.map(name => name.replace(LEADING_NEWLINE, '')).filter(name => name !== '')

    if (paths.length > bulk)
      continue

    const age = Math.max(0, now - Number(stamp) * 1000)
    const weight = halfLifeMs === 0 ? 1 : 0.5 ** (age / halfLifeMs)

    for (const path of paths) {
      const seen = churn.get(path) ?? { commits: 0, weight: 0 }

      churn.set(path, { commits: seen.commits + 1, weight: seen.weight + weight })
    }
  }

  return churn
}
