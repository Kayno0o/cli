it.each<ChangelogOptions>([
  {},
  { baseUrl: 'test.git.kaynooo.fr', baseUrlApi: 'api.test.git.kaynooo.fr', repo: 'user/changelog' },
])('should generate config while baseUrl is set to $baseUrl', async (proposedConfig) => {
  const { config, md } = await inside(repo.dir, async () => generate({ ...proposedConfig, from: repo.from, to: repo.to }))

  if (proposedConfig.baseUrl !== undefined)
    expect(config).toMatchObject(proposedConfig)
  else
    expect(config).toMatchObject({ baseUrl: 'git.kaynooo.fr', baseUrlApi: 'git.kaynooo.fr/api/v1' })

  const urls = md.match(regexToFindAllUrls)

  expect(urls?.length).toBeGreaterThan(0)
  expect(urls?.every(url => url.startsWith(`https://${config.baseUrl}`))).toBe(true)
})

it('reads the repo from the origin remote', async () => {
  expect(await inside(repo.dir, getGiteaRepo)).toBe('kaynooo/cli')
})

it('picks the last patch without rollup', async () => {
  expect(await inside(repo.dir, async () => getLastMatchingTag('v1.5.0', all, 'v%s'))).toBe('v1.4.2')
})

it('rolls a minor release back to the previous minor', async () => {
  expect(await inside(repo.dir, async () => getLastMatchingTag('v1.5.0', all, 'v%s', { minor: true }))).toBe('v1.4.0')
})

it('does not roll up a patch release', async () => {
  expect(await inside(repo.dir, async () => getLastMatchingTag('v1.4.3', all, 'v%s', { minor: true }))).toBe('v1.4.2')
})

it('rolls a major release back to the previous major line', async () => {
  // No `x.0.0` tag in the repo, so it falls back to the newest matching tag.
  expect(await inside(repo.dir, async () => getLastMatchingTag('v2.0.0', all, 'v%s', { major: true }))).toBe('v1.4.2')
})
