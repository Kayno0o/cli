import type { RawGitCommit } from '../src/changelog'
import type { AuthorInfo, Commit, ResolvedChangelogOptions } from '../src/types'
import { $ } from 'bun'
import { afterAll, beforeAll, beforeEach, describe, expect, it } from 'bun:test'
import { mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { parseGitCommit } from '../src/changelog'
import { loadConfig } from '../src/config'
import { generateDiscordPayload } from '../src/discord'
import { generateMarkdown } from '../src/markdown'

let dir: string

beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), 'changelogitea-notes-'))
})

afterAll(() => rm(dir, { recursive: true, force: true }))

async function options(overrides: Partial<ResolvedChangelogOptions> = {}) {
  return await loadConfig({ baseUrl: 'forge.example', repo: 'o/r', releaseRepo: 'o/r', from: 'v1.0.0', to: 'v1.1.0', ...overrides }, dir) as ResolvedChangelogOptions
}

let hash = 0

beforeEach(() => {
  hash = 0
})

function commit(message: string, body = ''): Commit {
  const raw: RawGitCommit = { message, body, shortHash: String(++hash).padStart(7, 'a'), author: { name: 'Ada', email: 'ada@example.com' } }

  return parseGitCommit(raw, { scopeMap: {} } as never)!
}

const ada: AuthorInfo = { name: 'Ada', email: 'ada@example.com', login: 'ada', avatar: 'https://forge.example/avatars/ada', commits: [] }

describe('ticket lines', () => {
  it('links each `#n - title` line of the body as an issue carrying its title', () => {
    const c = commit('fix: colors in pipes', 'Skips escapes off a TTY.\n#1 - colors writes escape codes into pipes\n#4 - NO_COLOR is ignored')

    expect(c.references.filter(ref => ref.type === 'issue')).toEqual([
      { type: 'issue', value: '#1', title: 'colors writes escape codes into pipes' },
      { type: 'issue', value: '#4', title: 'NO_COLOR is ignored' },
    ])
  })

  it('gives a subject reference the title of its body line instead of linking it twice', () => {
    const c = commit('fix: colors in pipes #1', '#1 - colors writes escape codes into pipes')

    expect(c.references.filter(ref => ref.type === 'issue')).toEqual([{ type: 'issue', value: '#1', title: 'colors writes escape codes into pipes' }])
  })
})

describe('forgejo markdown', () => {
  it('leads with a summary, puts breaking first and folds maintenance types', async () => {
    const md = generateMarkdown([
      commit('feat: undo command'),
      commit('build(deps): bump utils'),
      commit('fix!: drop the GitHub search', '#2 - co-authors 404'),
      commit('ci: use alpine'),
    ], await options(), [ada])

    expect(md).toBe([
      '> **1 breaking · 1 new · 2 maintenance** · by [@ada](https://forge.example/ada) · `v1.0.0` → `v1.1.0`',
      '',
      '### ⚠️ Breaking',
      '',
      '- Drop the GitHub search · [`aaaaaa3`](https://forge.example/o/r/commit/aaaaaa3) · [#2](https://forge.example/o/r/issues/2)',
      '',
      '### ✨ New',
      '',
      '- Undo command · [`aaaaaa1`](https://forge.example/o/r/commit/aaaaaa1)',
      '',
      '<details>',
      '<summary><b>🧹 Maintenance</b> · 1 build, 1 ci</summary>',
      '',
      '- **build(deps)**: Bump utils · [`aaaaaa2`](https://forge.example/o/r/commit/aaaaaa2)',
      '- **ci**: Use alpine · [`aaaaaa4`](https://forge.example/o/r/commit/aaaaaa4)',
      '',
      '</details>',
      '',
      '---',
      '',
      '<a href="https://forge.example/ada"><img src="https://forge.example/avatars/ada" width="28" height="28" alt="@ada"></a>',
      '',
      '<sub>[Full diff `v1.0.0...v1.1.0`](https://forge.example/o/r/compare/v1.0.0...v1.1.0) · generated by changelogitea</sub>',
    ].join('\n'))
  })

  it('drops the emojis from titles with emoji off', async () => {
    const md = generateMarkdown([commit('feat: a'), commit('ci: b')], await options({ emoji: false }))

    expect(md).toContain('### New\n')
    expect(md).toContain('<summary><b>Maintenance</b>')
  })

  it('shortens a full commit hash naming the range', async () => {
    const md = generateMarkdown([commit('feat: a')], await options({ from: 'fe0e9ea9a08a817b7ba849ebbecd556a274c79d1' }))

    expect(md).toContain('`fe0e9ea` → `v1.1.0`')
  })
})

describe('discord embed', () => {
  it('uses bold titles, inline issue titles and one maintenance line', async () => {
    const { embeds: [embed] } = generateDiscordPayload([
      commit('feat(undo): default to latest tag', '#3 - undo needs a tag'),
      commit('ci: use alpine'),
    ], await options(), [ada])

    expect(embed.title).toBe('r v1.1.0')
    expect(embed.url).toBe('https://forge.example/o/r/releases/tag/v1.1.0')
    expect(embed.description).toBe([
      '**✨ New**',
      '- **undo**: Default to latest tag · [`aaaaaa1`](https://forge.example/o/r/commit/aaaaaa1) · [#3 undo needs a tag](https://forge.example/o/r/issues/3)',
      '',
      '🧹 Maintenance *1 ci* · [full notes](https://forge.example/o/r/releases/tag/v1.1.0) · [diff](https://forge.example/o/r/compare/v1.0.0...v1.1.0)',
    ].join('\n'))
    expect(embed.footer).toEqual({ text: 'ada · v1.0.0 → v1.1.0', icon_url: 'https://forge.example/avatars/ada' })
  })

  it('stays under 4096 characters, saying how many commits were cut, and goes red on a breaking change', async () => {
    const commits = Array.from({ length: 80 }, (_, i) => commit(`feat: ${'long change '.repeat(6)}${i}`))

    commits.push(commit('fix!: breaking'))
    const { embeds: [embed] } = generateDiscordPayload(commits, await options())
    const shown = embed.description.split('\n').filter(line => line.startsWith('- ')).length

    expect(embed.description.length).toBeLessThanOrEqual(4096)
    expect(embed.description).toContain(`*…and ${81 - shown} more*`)
    expect(embed.description).toEndWith('[diff](https://forge.example/o/r/compare/v1.0.0...v1.1.0)')
    expect(embed.color).toBe(0xED4245)
  })
})

describe('config', () => {
  it('layers defaults, package.json, the config file and the options passed in', async () => {
    const cwd = await mkdtemp(join(dir, 'config-'))

    await writeFile(join(cwd, 'package.json'), JSON.stringify({ changelogitea: { group: 'multiple', tag: 'pkg-%s', titles: { maintenance: 'Chores' } } }))
    await writeFile(join(cwd, 'changelogitea.config.ts'), 'export default { tag: \'file-%s\', assets: [\'a\'], types: { feat: { title: \'Added\' } } }')

    const config = await loadConfig({ assets: ['b'], capitalize: undefined, emoji: false }, cwd)

    expect(config.group).toBe('multiple')
    expect(config.tag).toBe('file-%s')
    expect(config.assets).toEqual(['b'])
    expect(config.capitalize).toBe(true)
    expect(config.emoji).toBe(false)
    expect(config.titles).toEqual({ breakingChanges: '⚠️ Breaking', maintenance: 'Chores' })
    expect(config.types!.feat).toEqual({ title: 'Added' })
    expect(config.types!.ci).toEqual({ title: 'ci', folded: true })
  })
})

it('cli writes the notes to --output, reading negated flags', async () => {
  const output = join(dir, 'notes.md')

  await $`bun ${join(import.meta.dir, '../src/cli.ts')} --from fe0e9ea9a08a817b7ba849ebbecd556a274c79d1 --to 1f352da7c4763d4dba7861ef78443f9f731c6573 --no-emoji --no-contributors --output ${output}`.quiet()

  const md = await Bun.file(output).text()

  expect(md).toStartWith('> **1 fixed · 2 maintenance** · `fe0e9ea` → `1f352da`')
  expect(md).toContain('### Fixed')
})
